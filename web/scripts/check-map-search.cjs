const { chromium } = require('playwright-core');
const assert = require('node:assert/strict');
const baseUrl = process.env.MAP_TEST_URL || 'http://localhost:5174';
const gpsButtonName = 'Định vị vị trí hiện tại của tôi';
(async () => {
 const browser = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args:['--no-sandbox']});
 try {
 const context = await browser.newContext({viewport:{width:1440,height:900}, geolocation:{latitude:21.0185,longitude:105.834}, permissions:['geolocation']});
 const page = await context.newPage();
 page.on('pageerror', error => console.error('Page error:', error));
 await page.goto(`${baseUrl}/search`, {waitUntil:'domcontentloaded'});
 await page.getByRole('heading', {name:/10 phòng phù hợp/}).waitFor({timeout:30000});
 const input = page.getByRole('combobox', {name:'Tìm khu vực hoặc phòng'});
 await input.fill('Cau Giay');
 await page.getByRole('option', {name:'Cầu Giấy', exact:true}).waitFor();
 await input.press('ArrowDown');
 await input.press('Enter');
 await page.waitForURL(/location=/);
 await page.getByRole('heading', {name:/4 phòng phù hợp/}).waitFor();
 await page.getByRole('button',{name:'Giá',exact:true}).click();
 await page.getByRole('button',{name:'Dưới 3 triệu',exact:true}).click();
 await page.getByRole('heading',{name:/3 phòng phù hợp/}).waitFor();
 const map = page.locator('.leaflet-container').first();
 const box = await map.boundingBox();
 await page.mouse.move(box.x+box.width/2,box.y+box.height/2);
 await page.mouse.down();
 await page.mouse.move(box.x+box.width/2-100,box.y+box.height/2+60,{steps:10});
 await page.mouse.up();
 await page.getByRole('button',{name:'Tìm trong vùng bản đồ'}).click();
 await page.waitForURL(/south=/);
 await page.getByRole('button',{name:gpsButtonName}).click();
 await page.waitForURL(/radius=5/);
 await page.getByText('Bán kính quét: 5 km').waitFor();
 const circle = await page.locator('.leaflet-overlay-pane path[stroke="#0d9488"]').boundingBox();
 assert(circle && circle.x>=box.x && circle.y>=box.y && circle.x+circle.width<=box.x+box.width && circle.y+circle.height<=box.y+box.height);
 assert.equal(new URL(page.url()).searchParams.get('lat'), '21.0185');
 const marker = page.locator('.custom-price-marker').first();
 await marker.hover();
 await page.locator('.custom-price-marker.hovered').waitFor();
 await marker.click();
 await page.getByText('Đang chọn',{exact:true}).waitFor();
 const before = page.url();
 await page.getByText('Đang chọn',{exact:true}).click();
 await page.waitForURL(/\/room\//);
 await page.locator('.leaflet-container').first().waitFor();
 await page.goBack();
 await page.waitForURL(before);
 await page.reload({waitUntil:'domcontentloaded'});
 await page.getByText('Bán kính quét: 5 km').waitFor();
 assert.equal(page.url(),before);
 await page.goBack();
 await page.waitForURL(/south=/);
 await page.goForward();
 await page.waitForURL(before);
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:/Bản đồ/}).last().click();
 await page.locator('.leaflet-container').first().waitFor();
 console.log('Chromium desktop/mobile flow passed');

 const favorites = await context.newPage();
 await favorites.goto(`${baseUrl}/search`);
 const favorite = favorites.locator('[data-room-id]').first().getByRole('button', { name: 'Yêu thích', exact: true });
 await favorite.click();
 await favorites.locator('[data-room-id]').first().getByRole('button', { name: 'Bỏ yêu thích', exact: true }).waitFor();
 await favorites.goto(`${baseUrl}/favorites`);
 await favorites.getByRole('heading', {name:'Phòng yêu thích'}).waitFor();
 await favorites.getByText(/1 phòng đã lưu/).waitFor();
 console.log('Guest favorites flow passed');

 const deniedContext = await browser.newContext();
 const deniedPage = await deniedContext.newPage();
 await deniedPage.goto(`${baseUrl}/search`);
 await deniedPage.getByRole('button',{name:gpsButtonName}).click();
 await deniedPage.getByText(/Không thể lấy vị trí hiện tại/).waitFor();
 assert(!new URL(deniedPage.url()).searchParams.has('radius'));

 const slowPage = await deniedContext.newPage();
 await slowPage.addInitScript(() => {
   window.gpsCalls = 0;
   navigator.geolocation.getCurrentPosition = (_success, failure) => {
     window.gpsCalls++;
     setTimeout(() => failure({ code: 3 }), 1000);
   };
 });
 await slowPage.goto(`${baseUrl}/search`);
 const gpsButton = slowPage.getByRole('button',{name:gpsButtonName});
 await gpsButton.click();
 assert(await gpsButton.isDisabled());
 await gpsButton.evaluate(button => button.click());
 await slowPage.getByText('Định vị quá thời gian. Hãy thử lại.').waitFor();
 assert.equal(await slowPage.evaluate(() => window.gpsCalls),1);
 assert(await gpsButton.isEnabled());
 console.log('GPS denial, simulated timeout, and repeated click passed');

 const fallback = await context.newPage();
 await fallback.goto(`${baseUrl}/search?ai=1&keyword=${encodeURIComponent('Cầu Giấy dưới 3 triệu')}`);
 await fallback.getByRole('heading',{name:/3 phòng phù hợp/}).waitFor();
 await fallback.route('**/api/rooms/ai-search/details?*', route => route.fulfill({ status: 503 }));
 await fallback.getByRole('button',{name:'Mới nhất',exact:true}).click();
 await fallback.getByText('Đang dùng tiêu chí từ lần tìm trước').waitFor();
 await fallback.getByRole('heading',{name:/3 phòng phù hợp/}).waitFor();
 await fallback.getByRole('button',{name:'Tìm trong vùng bản đồ'}).click();
 await fallback.getByText('Đang dùng tiêu chí từ lần tìm trước').waitFor();
 assert(new URL(fallback.url()).searchParams.has('south'));
 await fallback.goto(`${baseUrl}/search?ai=1&keyword=zzzzzz`);
 await fallback.getByText('Tìm bằng từ khóa dự phòng').waitFor();
 console.log('AI fallback with and without cached criteria passed');
 } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
